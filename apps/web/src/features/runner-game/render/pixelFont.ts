export const glyph = (char: string): readonly string[] | undefined => GLYPHS[char.toUpperCase()];

export function pixelTextWidth(text: string): number {
   let width = 0;
   for (const char of text) {
      width += (glyph(char)?.[0].length ?? SPACE_WIDTH) + LETTER_GAP;
   }
   return Math.max(0, width - LETTER_GAP);
}

export function unsupportedGlyphs(text: string): string[] {
   return [...new Set([...text].filter((char) => char !== ' ' && !glyph(char)))];
}
